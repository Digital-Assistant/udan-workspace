#!/usr/bin/env bash
# Installs the toolchain the UDAN repositories need (jq, JDK 21, Node 22) into a
# user-owned prefix, without sudo. Meant for the Ubuntu WSL 2 distribution on
# Windows; it also works on any x86_64 Linux where these tools are missing.
#
# Usage: scripts/setup-wsl-toolchain.sh
#
# The tools go to ${UDAN_TOOLCHAIN_DIR:-$HOME/.local/udan}. An env file is
# written to $HOME/.config/udan/env.sh (JAVA_HOME and PATH); the udan.ps1
# wrapper sources it. Re-running is safe: an already installed tool is kept.
set -euo pipefail

PREFIX="${UDAN_TOOLCHAIN_DIR:-$HOME/.local/udan}"
BIN="$PREFIX/bin"
JDK_ROOT="$PREFIX/jdk"
NODE_ROOT="$PREFIX/node"
ENV_FILE="$HOME/.config/udan/env.sh"

log() { printf '==> %s\n' "$*"; }

case "$(uname -m)" in
  x86_64 | amd64) ARCH=x64 ;;
  aarch64 | arm64) ARCH=aarch64 ;;
  *) echo "unsupported architecture: $(uname -m)" >&2; exit 1 ;;
esac

mkdir -p "$BIN" "$JDK_ROOT" "$NODE_ROOT" "$(dirname "$ENV_FILE")"

# jq: a single static binary from the jqlang releases.
if [[ ! -x "$BIN/jq" ]]; then
  log "Installing jq"
  curl -fsSL -o "$BIN/jq" \
    "https://github.com/jqlang/jq/releases/latest/download/jq-linux-amd64"
  chmod +x "$BIN/jq"
else
  log "jq already installed"
fi

# JDK 21 (Temurin GA) from the Adoptium API.
JDK_DIR="$(find "$JDK_ROOT" -maxdepth 1 -mindepth 1 -type d -print -quit 2>/dev/null || true)"
if [[ -z "$JDK_DIR" || ! -x "$JDK_DIR/bin/java" ]]; then
  log "Installing JDK 21 (Temurin)"
  tmp="$(mktemp -d)"
  curl -fsSL -o "$tmp/jdk.tar.gz" \
    "https://api.adoptium.net/v3/binary/latest/21/ga/linux/$ARCH/jdk/hotspot/normal/eclipse?project=jdk"
  tar -xzf "$tmp/jdk.tar.gz" -C "$JDK_ROOT"
  rm -rf "$tmp"
  JDK_DIR="$(find "$JDK_ROOT" -maxdepth 1 -mindepth 1 -type d -print -quit)"
else
  log "JDK 21 already installed"
fi

# Node 22 from the official distribution.
NODE_DIR="$(find "$NODE_ROOT" -maxdepth 1 -mindepth 1 -type d -print -quit 2>/dev/null || true)"
if [[ -z "$NODE_DIR" || ! -x "$NODE_DIR/bin/node" ]]; then
  log "Installing Node 22"
  tmp="$(mktemp -d)"
  # Node names arm64 the same way, but the file suffix is linux-arm64 for aarch64.
  node_arch=x64
  [[ "$ARCH" == "aarch64" ]] && node_arch=arm64
  file="$(curl -fsSL https://nodejs.org/dist/latest-v22.x/ \
    | grep -oE "node-v22[0-9.]+-linux-$node_arch\.tar\.xz" | head -n 1)"
  [[ -n "$file" ]] || { echo "could not find the Node 22 tarball" >&2; exit 1; }
  curl -fsSL -o "$tmp/node.tar.xz" "https://nodejs.org/dist/latest-v22.x/$file"
  tar -xJf "$tmp/node.tar.xz" -C "$NODE_ROOT"
  rm -rf "$tmp"
  NODE_DIR="$(find "$NODE_ROOT" -maxdepth 1 -mindepth 1 -type d -print -quit)"
else
  log "Node 22 already installed"
fi

# Env file sourced by udan.ps1 and by the shell snippet below.
cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup-wsl-toolchain.sh. Do not edit by hand.
export JAVA_HOME="$JDK_DIR"
export PATH="$JDK_DIR/bin:$NODE_DIR/bin:$BIN:\$PATH"
EOF
log "Wrote $ENV_FILE"

# Load the tools in the current shell so the versions below prove the install.
# shellcheck disable=SC1090
source "$ENV_FILE"

# Make interactive WSL shells see the tools too, once.
if ! grep -q 'config/udan/env.sh' "$HOME/.bashrc" 2>/dev/null; then
  printf '\n# UDAN toolchain (JDK 21, Node 22, jq)\n[ -f "$HOME/.config/udan/env.sh" ] && . "$HOME/.config/udan/env.sh"\n' \
    >> "$HOME/.bashrc"
  log "Added the toolchain to ~/.bashrc"
fi

log "Installed versions"
java -version 2>&1 | head -n 1
node --version
npm --version
jq --version
log "Done. Run ./udan bootstrap next."
